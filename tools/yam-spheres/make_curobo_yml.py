"""Write tools/curobo/robots/yam/yam.yml (cuRobo robot_cfg, format 2.0) from yam_spheres.json.

The gripper's fingers have no joints in the URDF, so link_6 carries the gripper's spheres plus both tips' at
the open stroke (the conservative envelope). Needs only PyYAML.

    python make_curobo_yml.py
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "curobo" / "robots" / "yam" / "yam.yml"
LINKS = ["base_link", "link_1", "link_2", "link_3", "link_4", "link_5", "link_6"]
TCP = [0.0, 0.0, -0.1347, 0.0, 1.0, 0.0, 0.0]
"""link_6 -> fingertip centre, xyz + quat wxyz (the i2rt linear_4310 tool frame used by the earlier cuRobo port)."""


def main():
    doc = json.loads((HERE / "yam_spheres.json").read_text())
    body_of = {v: k for k, v in doc["link_names_urdf"].items()}
    spheres = {}
    for link in LINKS:
        src = (
            doc["spheres_link6_fingers_open"] if link == "link_6" else doc["spheres"][body_of[link]]
        )
        spheres[link] = [
            {"center": [float(x) for x in s["center"]], "radius": float(s["radius"])} for s in src
        ]
    ignore = {a: LINKS[i + 1 : i + 3] for i, a in enumerate(LINKS[:-1])}
    ignore["link_4"] = ignore["link_4"] + ["attached_object"]
    ignore["link_5"] = ignore["link_5"] + ["attached_object"]
    ignore["link_6"] = ["attached_object"]
    cfg = {
        "robot_cfg": {
            "kinematics": {
                "format_version": 2.0,
                "urdf_path": "yam_i2rt_arm.urdf",
                "asset_root_path": "",
                "base_link": "base_link",
                "tool_frames": ["tcp"],
                "extra_links": {
                    "tcp": {
                        "parent_link_name": "link_6",
                        "link_name": "tcp",
                        "joint_name": "tcp_joint",
                        "joint_type": "FIXED",
                        "fixed_transform": TCP,
                    },
                    "attached_object": {
                        "parent_link_name": "link_6",
                        "link_name": "attached_object",
                        "joint_name": "attach_joint",
                        "joint_type": "FIXED",
                        "fixed_transform": TCP,
                    },
                },
                "collision_link_names": LINKS + ["attached_object"],
                "collision_spheres": spheres,
                "extra_collision_spheres": {"attached_object": 4},
                "collision_sphere_buffer": 0.0,
                "self_collision_ignore": ignore,
                "self_collision_buffer": {k: 0.0 for k in LINKS + ["attached_object"]},
                "use_global_cumul": True,
                "cspace": {
                    "joint_names": [f"joint{i}" for i in range(1, 7)],
                    "default_joint_position": [0.0, 1.4, 1.2, 0.0, 1.1, 0.0],
                    "cspace_distance_weight": [1.0] * 6,
                    "null_space_weight": [1.0] * 6,
                    "max_acceleration": 15.0,
                    "max_jerk": 500.0,
                },
            }
        }
    }
    header = (
        "# Generated by tools/yam-spheres/make_curobo_yml.py from yam_spheres.json; do not edit by hand.\n"
        "# i2rt YAM 6-DoF + linear_4310 (fingers open, merged into link_6). Station bases: yam_spheres.json.\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        header + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=None, width=120)
    )
    print(OUT, sum(len(v) for v in spheres.values()), "spheres")


if __name__ == "__main__":
    main()
